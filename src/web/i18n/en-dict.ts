const EN_PATTERNS: ReadonlyArray<[RegExp, (...args: string[]) => string]> = [
  [/^随设备自动切换，当前为浅色。$/, () => 'Follows system appearance (currently Light).'],
  [/^随设备自动切换，当前为深色。$/, () => 'Follows system appearance (currently Dark).'],
  [/^始终使用浅色模式。$/, () => 'Always uses Light mode.'],
  [/^始终使用深色模式。$/, () => 'Always uses Dark mode.'],
  [/^随系统语言切换，当前为(.+)。$/, (_m, lang) => `Follows system language (currently ${lang}).`],
  [/^最多保存\s*(\d+)\s*个自定义主题$/, (_m, n) => `Up to ${n} custom themes can be saved`],
  [/^已导入\s*(\d+)\s*个主题，可在对应模式中选择$/, (_m, n) => `Imported ${n} theme(s) into the corresponding mode`],
  [/^在(.+)支持$/, (_m, name) => `Support on ${name}`],
  [/^(.+)的赞赏码$/, (_m, name) => `${name}'s Reward QR`],
  [/^删除“(.+)”？$/, (_m, name) => `Delete "${name}"?`],
  [/^选择(.+)$/, (_m, name) => `Select ${EN_EXACT[name] ?? name}`],
  [/^导出(.+)$/, (_m, name) => `Export ${EN_EXACT[name] ?? name}`],
  [/^编辑(.+)$/, (_m, name) => `Edit ${EN_EXACT[name] ?? name}`],
  [/^删除(.+)$/, (_m, name) => `Delete ${EN_EXACT[name] ?? name}`],
  [/^添加(浅色|深色)主题$/, (_m, mode) => `Add ${mode === '浅色' ? 'Light' : 'Dark'} Theme`],
  [/^(\d+)\s*分钟前$/, (_m, n) => `${n}m ago`],
  [/^(\d+)\s*小时前$/, (_m, n) => `${n}h ago`],
  [/^(\d+)\s*天前$/, (_m, n) => `${n}d ago`],
  [/^刚刚$/, () => 'Just now'],
  [/^共\s*(\d+)\s*条(?:消息|记录)?$/, (_m, n) => `${n} items`],
  [/^(\d+)\s*个(?:设备|会话|成员|联系人)$/, (_m, n) => `${n}`],
  [/^剩余\s*(\d+)\s*秒$/, (_m, n) => `${n}s left`],
  [/^UID\s*(\d+)\s*·\s*管理员$/, (_m, id) => `UID ${id} · Admin`],
];

export function translateZhToEn(raw: string): string | null {
  const trimmed = raw.trim();
  if (!trimmed) return null;
  const exact = EN_EXACT[trimmed];
  if (exact) return raw.replace(trimmed, exact);
  for (const [pattern, replacer] of EN_PATTERNS) {
    const match = trimmed.match(pattern);
    if (match) {
      const replaced = replacer(...match);
      return raw.replace(trimmed, replaced);
    }
  }
  return null;
}
